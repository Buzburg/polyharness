// Generated filters are opt-in checks, not an execution sandbox.
const shellQuote = value => "'" + value.replaceAll("'", "'\\''") + "'";

export function generatePreCommitHook(config) {
  const paths = config.safety?.protected_paths || [];
  const code = `const {execFileSync}=require('node:child_process');
const protectedPaths=${JSON.stringify(paths)};
const files=execFileSync('git',['diff','--cached','--name-only','-z'],{encoding:'utf8'}).split('\\0').filter(Boolean);
for(const file of files){for(const raw of protectedPaths){const p=raw.replace(/\\/$/,'');if(file===p||file.startsWith(p+'/')){console.error('Commit blocked: protected path '+JSON.stringify(file));process.exit(1);}}}`;
  return `#!/bin/sh\n# Generated by polyharness. Requires Node.js.\nexec node -e ${shellQuote(code)}\n`;
}

export function generateSafeExecScript(config) {
  const patterns = config.safety?.destructive_commands_deny || [];
  const code = `const {spawnSync}=require('node:child_process');
const args=process.argv.slice(1);
if(!args.length){console.error('Usage: safe-exec command [arguments]');process.exit(2);}
const patterns=${JSON.stringify(patterns)};
const command=args.join(' ');
if(patterns.some(p=>p&&command.includes(p))){console.error('Execution blocked by configured pattern');process.exit(126);}
const result=spawnSync(args[0],args.slice(1),{stdio:'inherit',shell:false});
if(result.error){console.error(result.error.message);process.exit(127);}
process.exit(result.status===null?1:result.status);`;
  return `#!/bin/sh\n# Generated by polyharness. Literal pattern filter, not a sandbox.\nexec node -e ${shellQuote(code)} -- "$@"\n`;
}
